-- ============================================================
-- TorgStore Analytics — Migration 002
-- Добавляет поле "Не реализовано" из новой выгрузки CRM.
--
-- Семантика (подтверждено пользователем):
--   "Не реализовано" = лиды, которые менеджер ЯВНО закрыл финальным
--   статусом "закрыто, не реализовано" (окончательно проиграно).
--   Остаток (Лиды − Продажи − Не реализовано) = лиды ещё в работе,
--   НЕ являются потерей.
--
-- До этой миграции сайт считал "слито" = Лиды − Продажи, что смешивало
-- реально проигранные лиды с теми, что просто ещё не закрыты.
-- Это накопительная (idempotent) миграция — безопасно запускать повторно.
-- ============================================================

ALTER TABLE session_totals ADD COLUMN IF NOT EXISTS not_realized NUMERIC;
ALTER TABLE source_rows    ADD COLUMN IF NOT EXISTS not_realized NUMERIC;

COMMENT ON COLUMN session_totals.not_realized IS
  'Лиды со статусом "закрыто, не реализовано" (окончательно проиграно), из колонки CRM "Не реализовано". NULL = период загружен до появления этого поля в выгрузке.';
COMMENT ON COLUMN source_rows.not_realized IS
  'То же самое на уровне отдельного источника/кампании.';
