-- Кеш «уже прочитанных» лидов для дельта-выгрузки Причин отказа.
--
-- Контекст (12.08.2026): скрипт §6.3 раннбука раньше каждый день перечитывал
-- leads/details ПО ВСЕМ лидам с 1 числа месяца заново (даже те, что уже
-- читал вчера/позавчера) — 166 запросов на 10-дневный частичный август,
-- растёт пропорционально дню месяца. Причина отказа — финальное поле лида
-- (назначается один раз при переводе в «Не реализовано», дальше не
-- меняется), значит повторное чтение уже виденных лидов — чистая трата
-- запросов при том же самом правиле 3с (см. CLAUDE.md).
--
-- Эта таблица — ТОЛЬКО внутренний кеш скрипта выгрузки, не связана с
-- decline_reason_stats и НЕ меняет её контракт: decline_reason_stats
-- по-прежнему хранит агрегат (manager, period, pipeline, reason → count),
-- decline_reasons.py и фронтенд не читают эту таблицу вообще. Роль кеша:
-- скрипт §6.3 фильтрует список лидов периода ПЕРЕД тем, как решить, каких
-- лидов реально идти читать в CRM — уже закешированные не запрашиваются
-- повторно, агрегация decline_reason_stats строится из кеша+новых вместе.
--
-- Идемпотентная миграция — безопасно запускать повторно.
-- ============================================================

CREATE TABLE IF NOT EXISTS decline_reason_lead_cache (
    lead_id       BIGINT PRIMARY KEY,                       -- CRM lead.id (числовое CRM-пространство, не UUID сайта)
    manager_id    UUID NOT NULL REFERENCES managers(id),
    reason        TEXT NOT NULL,                            -- значение поля «Причина отказа» на момент первого чтения, или 'Не указана'
    pipeline      TEXT NOT NULL DEFAULT 'Отдел первичных продаж',
    lead_created_at TIMESTAMPTZ,                             -- create.created_at из CRM — для отладки/аудита диапазонов
    fetched_at    TIMESTAMPTZ DEFAULT now(),                 -- когда реально был сделан CRM-запрос leads/details по этому лиду
    created_at    TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_decline_reason_lead_cache_manager ON decline_reason_lead_cache(manager_id);

COMMENT ON TABLE decline_reason_lead_cache IS
  'Внутренний кеш скрипта выгрузки Причин отказа (§6.3 раннбука) — lead_id уже прочитанных лидов, чтобы не перечитывать их из CRM каждый день заново. НЕ читается ни decline_reasons.py, ни фронтендом — только скриптом сбора данных перед решением, каких лидов идти запрашивать. Не путать с decline_reason_stats (агрегированная витрина для сайта).';
